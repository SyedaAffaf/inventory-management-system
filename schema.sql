-- Run this script in Supabase SQL Editor.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 2 and 100),
  sku text not null,
  category text not null default 'General',
  quantity integer not null default 0 check (quantity >= 0),
  price numeric(12,2) not null default 0 check (price >= 0),
  reorder_level integer not null default 5 check (reorder_level >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, sku)
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  details text not null,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.activity_logs enable row level security;

-- The Express API uses a server-side service role key and verifies the user's JWT.
-- These policies also protect direct client access if you add it later.
create policy "Users can view their own products"
on public.products for select using (auth.uid() = user_id);
create policy "Users can insert their own products"
on public.products for insert with check (auth.uid() = user_id);
create policy "Users can update their own products"
on public.products for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete their own products"
on public.products for delete using (auth.uid() = user_id);

create policy "Users can view their own activity"
on public.activity_logs for select using (auth.uid() = user_id);
create policy "Users can insert their own activity"
on public.activity_logs for insert with check (auth.uid() = user_id);
